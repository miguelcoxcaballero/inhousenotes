// Split profile (6.2, scripts/split-wasm.mjs): records which wasm functions run while the app boots and shows
// Welcome or Home, and writes them to scripts/wasm-split-keep.txt (they stay in the first part of ihn.wasm).
// Only with an instrumented build:  IHN_SPLIT_PROFILE=1 npm run build && IHN_SPLIT_PROFILE=1 npx playwright test zz-split-profile
// then `npm run build` again for the split build. A stale list only makes the second part load earlier.
import { readFileSync, writeFileSync } from 'node:fs';
import { test, expect, seedSession, fixtures } from '../mock/fixtures.mjs';
import { stableName } from '../../../scripts/split-wasm.mjs';

test.skip(process.env.IHN_SPLIT_PROFILE !== '1', 'profiling build only');
test.use({ serviceWorkers: 'block' });

const marked = new Set();
const collect = async page => { for (const i of await page.evaluate(() => window.__IHN_SPLIT_MARKS__())) marked.add(i); };
const ready = async page => {
  await page.waitForFunction(() => window.__IHN_TEST_API__ && window.__IHN_SPLIT_MARKS__);
  expect(await page.evaluate(() => window.__IHN_TEST_API__.ready())).toBe(true);
};

test('signed out: Welcome', async ({ page }) => {
  await page.route('https://accounts.google.com/**', route => route.fulfill({ contentType: 'text/javascript', body: '' }));
  await page.goto('/?e2e=1');
  await ready(page);
  await expect(page.locator('#welcome-view')).toBeVisible();
  await page.waitForTimeout(1500);
  await collect(page);
});

test('signed in: Home with a library, its tabs, then idle', async ({ page, context, mock }) => {
  fixtures.library(mock);
  await seedSession(context, mock);
  await page.goto('/?e2e=1');
  await ready(page);
  await expect(page.locator('#drive-home')).toBeVisible();
  await expect(page.locator('#drive-recents .drive-card').first()).toBeVisible();
  await page.waitForTimeout(2500);
  await collect(page);
});

// The production build (no `?e2e=1`): its boot differs a little from the test build's.
const markedProd = new Set();
const collectProd = async page => {
  await page.waitForFunction(() => window.__IHN_SPLIT_MARKS__);
  for (const i of await page.evaluate(() => window.__IHN_SPLIT_MARKS__())) markedProd.add(i);
};

test('production build, signed out: Welcome', async ({ page }) => {
  await page.route('https://accounts.google.com/**', route => route.fulfill({ contentType: 'text/javascript', body: '' }));
  await page.goto('/');
  await expect(page.locator('#welcome-view')).toBeVisible();
  await page.waitForTimeout(1500);
  await collectProd(page);
});

test('production build, signed in: Home with a library, then idle', async ({ page, context, mock }) => {
  fixtures.library(mock);
  await seedSession(context, mock);
  await page.goto('/');
  await expect(page.locator('#drive-recents .drive-card').first()).toBeVisible();
  await page.waitForTimeout(2500);
  await collectProd(page);
});

test.afterAll(() => {
  const named = (file, set) => { const names = JSON.parse(readFileSync(file, 'utf8')); return [...set].map(i => names[i]); };
  // Unnamed functions (their index as name) are always kept by split-wasm.mjs.
  const keep = [...new Set([...named('build/split-names.json', marked), ...named('build/split-names-prod.json', markedProd)]
    .filter(name => name && !/^\d+$/.test(name)).map(stableName))].sort();
  writeFileSync('scripts/wasm-split-keep.txt', [
    '# Functions that stay in the first part of ihn.wasm (scripts/split-wasm.mjs): what boots the app and shows Welcome',
    '# or Home. Generated by tests/v6/e2e/zz-split-profile.spec.mjs; every other function moves to wasm/ihn-2.wasm.',
    ...keep, ''].join('\n'));
  console.log(`split profile: ${keep.length} functions kept`);
});
