// Writes <out>/offline-assets.js: the shell the v6 service worker precaches (ARCHITECTURE §7.3, §12).
// Usage: node scripts/build-offline-assets.mjs [--out build]   (run from the repository root; the build does)
import { existsSync } from 'node:fs';
import { mkdir, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
const out=process.argv.includes('--out')?process.argv[process.argv.indexOf('--out')+1]:'build';
const roots=['host','vendor/pdfjs','vendor/pdf-lib','vendor/fonts'];
const files=['index.html','boot.js','wasm/ihn.wasm','offline-v5.css','shared/inhouse-services-updater/updater.css',
    'shared/inhouse-services-updater/updater.js','icons/welcome-pages.svg',
    // Template SVGs join the shell when W2.3 adds them.
    ...['icons/agenda.svg','icons/diary.svg'].filter(path=>existsSync(path))];
async function walk(path){for(const entry of (await readdir(path,{withFileTypes:true})).sort((a,b)=>a.name<b.name?-1:1)){
    const name=join(path,entry.name).replaceAll('\\','/');if(entry.isDirectory())await walk(name);else if(!/\.(md|map|py|zip|pdf)$/i.test(name)&&!name.includes('LICENSE'))files.push(name);
}}
for(const root of roots)await walk(root);
await mkdir(out,{recursive:true});
await writeFile(join(out,'offline-assets.js'),`/* Generated by scripts/build-offline-assets.mjs. */\nself.INHOUSE_OFFLINE_ASSETS=${JSON.stringify([...new Set(files)].sort().map(f=>'/'+f),null,2)};\n`);
console.log(`Offline shell: ${files.length} assets`);
