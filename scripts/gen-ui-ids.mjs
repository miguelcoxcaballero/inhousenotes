// Generates rust/crates/ihn-app/src/ui_ids.rs: one fixed DOM handle per `id` of index.html (ARCHITECTURE §3.6).
// The markup is 5.18.0's and does not change, so the table is committed; `--check` (run by the build) fails when
// it is stale.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const target = `${root}rust/crates/ihn-app/src/ui_ids.rs`;
const FIRST = 16; // handles 1..4 are document, window, <html>, <body>; 5..15 reserved

const html = (await readFile(`${root}index.html`, 'utf8')).replace(/<style[\s\S]*?<\/style>/g, '');
const ids = [...new Set([...html.matchAll(/<[a-zA-Z][^<>]*?\sid="([^"]+)"/g)].map(match => match[1]))];
const names = new Map();
for (const id of ids) {
  const name = id.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/[^A-Za-z0-9]+/g, '_').toUpperCase();
  if (!/^[A-Z]/.test(name) || names.has(name)) throw new Error(`Cannot name id "${id}" (${name})`);
  names.set(name, id);
}
if (FIRST + ids.length > 1024) throw new Error('Ui handles would reach abi::FIRST_DYNAMIC_NODE');

const lines = [
  '//! Generated by scripts/gen-ui-ids.mjs from index.html — do not edit. One fixed handle per element id of the',
  '//! 5.18.0 markup (ARCHITECTURE §3.6), bound once at boot by `App::init`.',
  '',
  'use crate::abi::Node;',
  '',
  '/// The static nodes of `index.html`: `Ui::DRIVE_HOME` is `document.getElementById("drive-home")`.',
  'pub struct Ui;',
  '',
  '#[rustfmt::skip]',
  'impl Ui {',
  `    /// Handle of \`IDS[0]\`; \`IDS[i]\` is bound to \`Node(FIRST + i)\`.`,
  `    pub const FIRST: u32 = ${FIRST};`,
  ...[...names.keys()].map((name, index) => `    pub const ${name}: Node = Node(${FIRST + index});`),
  `    pub const IDS: [&'static str; ${ids.length}] = [`,
  ...ids.map(id => `        ${JSON.stringify(id)},`),
  '    ];',
  '}',
  ''
];
const source = lines.join('\n');
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8').catch(() => '') !== source) {
    throw new Error('ui_ids.rs is stale: run `node scripts/gen-ui-ids.mjs`');
  }
} else {
  await writeFile(target, source);
  console.log(`Ui table: ${ids.length} ids`);
}
