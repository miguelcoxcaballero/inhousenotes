//! Asset manifest (`data/assets.toml`) and the lock file of pinned hashes.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct Manifest {
    #[serde(rename = "asset")]
    pub assets: Vec<AssetEntry>,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct FileSource {
    pub url: String,
    pub path: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct PolyHavenSource {
    pub id: String,
    pub res: String,
    pub format: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct AmbientCgSource {
    pub id: String,
    pub res: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct SketchfabSource {
    pub uid: String,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct OsmSource {
    pub bbox: [f64; 4],
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct TerrariumSource {
    pub z: u32,
    pub x: u32,
    pub y: u32,
    pub tiles: u32,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ManualSource {
    pub url: String,
    pub note: String,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum AssetKind {
    Map,
    Terrain,
    Vehicle,
    Weapon,
    Prop,
    Animation,
    Character,
    Sky,
    Material,
}

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct AssetEntry {
    pub id: String,
    pub name: String,
    pub kind: AssetKind,
    pub license: String,
    pub author: String,
    pub homepage: String,
    #[serde(default)]
    pub zip: Option<String>,
    #[serde(default)]
    pub page: Option<String>,
    #[serde(default)]
    pub include: Vec<String>,
    #[serde(default)]
    pub strip: Option<String>,
    #[serde(default)]
    pub files: Vec<FileSource>,
    #[serde(default)]
    pub polyhaven: Option<PolyHavenSource>,
    #[serde(default)]
    pub ambientcg: Option<AmbientCgSource>,
    #[serde(default)]
    pub sketchfab: Option<SketchfabSource>,
    #[serde(default)]
    pub osm: Option<OsmSource>,
    #[serde(default)]
    pub terrarium: Option<TerrariumSource>,
    #[serde(default)]
    pub manual: Option<ManualSource>,
}

impl AssetEntry {
    /// CC0 and public-domain content needs no credit.
    pub fn needs_attribution(&self) -> bool {
        !self.license.trim().eq_ignore_ascii_case("CC0-1.0")
    }
}

impl Manifest {
    pub fn load(path: &Path) -> Result<Self, String> {
        let text = std::fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
        let m: Manifest = toml::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))?;
        for a in &m.assets {
            let sources = [
                a.zip.is_some(),
                !a.files.is_empty(),
                a.polyhaven.is_some(),
                a.ambientcg.is_some(),
                a.sketchfab.is_some(),
                a.osm.is_some(),
                a.terrarium.is_some(),
                a.manual.is_some(),
            ];
            if sources.iter().filter(|s| **s).count() != 1 {
                return Err(format!("asset {} must have exactly one source", a.id));
            }
        }
        Ok(m)
    }

    pub fn get(&self, id: &str) -> Option<&AssetEntry> {
        self.assets.iter().find(|a| a.id == id)
    }

    /// What a player needs: every asset that downloads without an account
    /// or a browser, keeping only [`PLAY_AVATARS`] of the Rocketbox people
    /// (each is ~90 MB of uncompressed textures).
    pub fn play_set(&self) -> Vec<&AssetEntry> {
        self.assets
            .iter()
            .filter(|a| a.sketchfab.is_none() && a.manual.is_none())
            .filter(|a| !a.id.starts_with("rocketbox_") || PLAY_AVATARS.contains(&a.id.as_str()))
            .collect()
    }
}

/// Rocketbox avatars in the player download: the player's own first choice
/// plus a varied crowd.
pub const PLAY_AVATARS: [&str; 4] = ["rocketbox_male_adult_08", "rocketbox_business_male_01", "rocketbox_female_adult_05", "rocketbox_business_female_01"];

/// Play-set assets not yet downloaded under `root`.
pub fn missing_play_assets(root: &Path) -> Vec<String> {
    let Ok(m) = Manifest::load(&root.join("data/assets.toml")) else { return Vec::new() };
    m.play_set().into_iter().filter(|a| !asset_dir(root, &a.id).exists()).map(|a| a.id.clone()).collect()
}

/// `data/assets.lock.toml`: SHA-256 of every downloaded file, keyed by
/// `asset_id/relative_path`.
#[derive(Clone, Debug, Default, Serialize, Deserialize)]
pub struct Lock {
    #[serde(default)]
    pub files: BTreeMap<String, String>,
}

impl Lock {
    pub fn load(path: &Path) -> Self {
        std::fs::read_to_string(path).ok().and_then(|t| toml::from_str(&t).ok()).unwrap_or_default()
    }

    pub fn save(&self, path: &Path) -> std::io::Result<()> {
        let header = "# Generated by forja_fetch. Pins the SHA-256 of downloaded files.\n";
        std::fs::write(path, format!("{header}{}", toml::to_string_pretty(self).expect("serializable")))
    }
}

/// Engine root: the directory holding `data/assets.toml`, searched upwards
/// from the current directory, then from the executable. A release keeps
/// `data/` next to the executable, which wins so it runs from anywhere.
pub fn find_engine_root() -> Option<PathBuf> {
    let exe = std::env::current_exe().ok().and_then(|e| e.parent().map(Path::to_path_buf));
    if let Some(dir) = exe.as_ref().filter(|d| d.join("data/assets.toml").is_file()) {
        return Some(dir.clone());
    }
    std::env::current_dir().ok().and_then(search_up).or_else(|| exe.and_then(search_up))
}

fn search_up(mut dir: PathBuf) -> Option<PathBuf> {
    loop {
        if dir.join("data/assets.toml").is_file() {
            return Some(dir);
        }
        if dir.join("engine/data/assets.toml").is_file() {
            return Some(dir.join("engine"));
        }
        if !dir.pop() {
            return None;
        }
    }
}

/// Where downloads go: `<root>/assets/downloaded/<id>/`.
pub fn asset_dir(root: &Path, id: &str) -> PathBuf {
    root.join("assets/downloaded").join(id)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn shipped_manifest_parses() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../data/assets.toml");
        let m = Manifest::load(&path).unwrap();
        assert!(m.assets.len() >= 10);
        for kind in [AssetKind::Map, AssetKind::Vehicle, AssetKind::Weapon, AssetKind::Animation] {
            assert!(m.assets.iter().any(|a| a.kind == kind), "no {kind:?} assets");
        }
        let mut ids: Vec<_> = m.assets.iter().map(|a| &a.id).collect();
        ids.sort();
        ids.dedup();
        assert_eq!(ids.len(), m.assets.len(), "duplicate ids");
    }
}
