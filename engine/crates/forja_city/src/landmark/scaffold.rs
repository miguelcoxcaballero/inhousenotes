//! Draft `landmark.toml` from the real data: one mass per OSM part (they
//! replace their outline, as in OSM Simple 3D Buildings) or per outline
//! without parts, heights from tags or Catastro floors, a roof from
//! `roof:shape`, the main facade from the photo cameras or the street
//! side, and a `[[view]]` per photo with a known camera. A starting point
//! for modelling, never the final model.

use std::fmt::Write;

use forja_math::Vec2;

use super::footprint::{Footprint, FpPoly, Sources};
use super::poly::{self, Shape};

fn esc(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

fn roof_shape(tag: Option<&str>) -> Option<&'static str> {
    Some(match tag? {
        "gabled" => "gable",
        "hipped" | "half-hipped" => "hip",
        "pyramidal" => "pyramid",
        "dome" | "onion" => "dome",
        "skillion" => "shed",
        "round" => "barrel",
        "cone" | "conical" => "cone",
        "mansard" => "mansard",
        _ => return None,
    })
}

/// Height estimate of an outline: OSM tags, else the tallest Catastro
/// parcel overlapping it.
fn height_of(p: &FpPoly, fp: &Footprint) -> (f32, &'static str) {
    if let Some(h) = p.tag_height() {
        return (h, "OSM height/levels tag");
    }
    let c = poly::centroid(&p.shape.outer);
    let floors = fp.catastro.iter().filter(|q| q.shape.contains(c) || p.shape.contains(poly::centroid(&q.shape.outer))).filter_map(|q| q.floors_above).fold(0.0f32, f32::max);
    if floors > 0.0 {
        return (floors * 3.2 + 1.0, "Catastro floors x 3.2 m + 1 m");
    }
    (12.0, "placeholder: no height data")
}

/// Fraction of `outline` covered by the union of `parts`.
fn covered(outline: &Shape, parts: &[&FpPoly]) -> f32 {
    if parts.is_empty() {
        return 0.0;
    }
    let ps: Vec<Shape> = parts.iter().map(|p| p.shape.clone()).collect();
    let inter = poly::boolean(std::slice::from_ref(outline), &ps, poly::BoolOp::Intersection);
    inter.iter().map(|s| s.area()).sum::<f32>() / outline.area().max(1e-3)
}

/// Main facade of outline 0: the edge the photos look at most, else the
/// longest edge facing a street (not backing onto a neighbour).
fn main_facade(fp: &Footprint, sources: Option<&Sources>) -> (String, &'static str) {
    let Some(o) = fp.outlines.first() else { return ("\"longest\"".into(), "no outline") };
    let r = &o.shape.outer;
    let n = r.len();
    let edge = |i: usize| (r[i], r[(i + 1) % n], poly::edge_normal(r, i));
    let cams: Vec<Vec2> = sources.map(|s| s.photos.iter().filter_map(|p| p.camera).collect()).unwrap_or_default();
    if !cams.is_empty() {
        let mut best = (0usize, 0.0f32);
        for i in 0..n {
            let (a, b, nr) = edge(i);
            let mid = (a + b) * 0.5;
            let len = (b - a).length();
            let score: f32 = cams.iter().map(|c| {
                let d = *c - mid;
                let dist = d.length().max(1.0);
                len * (nr.dot(d / dist)).max(0.0) / dist.sqrt()
            }).sum();
            if score > best.1 {
                best = (i, score);
            }
        }
        if best.1 > 0.0 {
            return (format!("{}", best.0), "the edge most photo cameras look at");
        }
    }
    // Street-facing: nothing built within 3 m in front of the edge.
    let free = |i: usize| {
        let (a, b, nr) = edge(i);
        [0.25f32, 0.5, 0.75].iter().all(|t| {
            let q = a.lerp(b, *t) + nr * 3.0;
            !fp.context.iter().chain(fp.outlines.iter().skip(1)).any(|c| c.shape.contains(q))
        })
    };
    let mut best: Option<(usize, f32)> = None;
    for i in 0..n {
        let (a, b, _) = edge(i);
        let l = (b - a).length();
        if free(i) && best.is_none_or(|bb| l > bb.1) {
            best = Some((i, l));
        }
    }
    match best {
        Some((i, _)) => (format!("{i}"), "the longest edge facing a street"),
        None => ("\"longest\"".into(), "every edge has a neighbour: check"),
    }
}

/// Height of a part: its tags, else the Catastro parcels it overlaps.
fn part_height(p: &FpPoly, fp: &Footprint) -> Option<(f32, &'static str)> {
    if let Some(h) = p.tag_height() {
        return Some((h, "OSM height/levels tag"));
    }
    let (h, why) = height_of(p, fp);
    (why != "placeholder: no height data").then_some((h, why))
}

/// Draft spec text.
pub fn draft(slug: &str, fp: Option<&Footprint>, sources: Option<&Sources>) -> String {
    let mut s = String::new();
    let name = fp.and_then(|f| f.outlines.iter().find_map(|o| o.tag("name").map(|n| n.to_string()))).unwrap_or_else(|| slug.to_string());
    let _ = writeln!(s, "# Draft generated by `landmark init` from footprint.json: massing only.");
    let _ = writeln!(s, "# Refine following data/landmarks/README.md (roofs, towers, openings, details).\n");
    let (mf, mf_why) = fp.map(|f| main_facade(f, sources)).unwrap_or(("\"longest\"".into(), "no footprint"));
    let _ = writeln!(s, "[landmark]\nname = \"{}\"\nslug = \"{}\"\nmain_facade = {mf}   # {mf_why}\n", esc(&name), esc(slug));
    let _ = writeln!(s, "[defaults]\nmaterial = \"stone\"\n");
    let _ = writeln!(s, "[material.stone]\nkind = \"ashlar\"\ntint = \"#e3d8c2\"\nweathering = 0.3\n");
    let _ = writeln!(s, "[material.roof]\nkind = \"roof_tiles\"\n");
    if let Some(fp) = fp {
        // Parts drawn over an outline replace it (OSM Simple 3D Buildings).
        let parts_of = |o: &FpPoly| -> Vec<&FpPoly> { fp.parts.iter().filter(|p| o.shape.contains(poly::centroid(&p.shape.outer)) || p.shape.contains(poly::centroid(&o.shape.outer))).collect() };
        for (i, o) in fp.outlines.iter().enumerate() {
            let (h, why) = height_of(o, fp);
            let cover = covered(&o.shape, &parts_of(o));
            let replaced = cover >= 0.5;
            let _ = writeln!(s, "[[element]]\ntype = \"mass\"\nname = \"outline{i}\"\npolygon = \"outline:{i}\"   # {} ({:.0} m2)\nheight = {:.1}   # {why}\ncornice = \"cornice\"", esc(&o.id), o.shape.area(), h);
            if replaced {
                let _ = writeln!(s, "enabled = false   # {:.0}% covered by building:parts below, which replace it", cover * 100.0);
            }
            match roof_shape(o.tag("roof:shape")) {
                Some(r) => {
                    let _ = writeln!(s, "roof = {{ shape = \"{r}\", pitch = 30 }}\n");
                }
                None => {
                    let _ = writeln!(s);
                }
            }
        }
        for (i, p) in fp.parts.iter().enumerate() {
            let Some((h, why)) = part_height(p, fp) else {
                let _ = writeln!(s, "# part:{i} ({}) has no height tag and no Catastro floors: model it from the photos\n", esc(&p.id));
                continue;
            };
            let y0 = p.tag_min_height().unwrap_or(0.0).max(0.0);
            if h <= y0 + 0.5 {
                continue;
            }
            let _ = writeln!(s, "[[element]]\ntype = \"mass\"\nname = \"part{i}\"\npolygon = \"part:{i}\"   # {} {}\ny0 = {:.1}\ny1 = {:.1}   # {why}", esc(&p.id), esc(p.tag("building:part").unwrap_or("")), y0, h);
            if let Some(r) = roof_shape(p.tag("roof:shape")) {
                let _ = writeln!(s, "roof = {{ shape = \"{r}\" }}");
            }
            let _ = writeln!(s);
        }
        if fp.outlines.is_empty() {
            let _ = writeln!(s, "# footprint.json has no outlines: add masses with literal polygons.\n");
        }
    } else {
        let _ = writeln!(s, "# No footprint.json yet: add masses with literal polygons [[x, z], ...].\n");
    }
    if let Some(src) = sources {
        for p in &src.photos {
            match p.camera {
                Some(c) => {
                    let _ = writeln!(s, "[[view]]\nphoto = \"{}\"\neye = [{:.1}, 1.6, {:.1}]\ntarget = [0.0, 10.0, 0.0]   # aim at the main feature\nfocal_35mm = 28\n", esc(&p.file), c.x, c.y);
                }
                None => {
                    let _ = writeln!(s, "# [[view]]\n# photo = \"{}\"   # estimate eye/target from the photo (README)\n", esc(&p.file));
                }
            }
        }
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn draft_parses() {
        let fp = Footprint::parse(
            r#"{"anchor":[0,0],"outlines":[{"id":"way/9","tags":{"name":"Torre","height":"20","roof:shape":"pyramidal"},"outer":[[0,0],[8,0],[8,8],[0,8]]}],
            "parts":[{"id":"way/10","tags":{"building:part":"yes","height":"30","min_height":"20"},"outer":[[2,2],[6,2],[6,6],[2,6]]}]}"#,
            "t",
        )
        .unwrap();
        let src = Sources::parse("[[photo]]\nfile = \"photos/a.jpg\"\ncamera = [5.0, 40.0]\n").unwrap();
        let text = draft("torre", Some(&fp), Some(&src));
        let spec = crate::landmark::parse::parse_spec(&text, "draft").unwrap_or_else(|e| panic!("{e}\n{text}"));
        assert_eq!(spec.element.len(), 2);
        // The part covers a quarter of the outline: the outline stays on.
        assert!(!text.contains("enabled = false"), "{text}");
        assert_eq!(spec.view.len(), 1);
        let m = crate::landmark::build::build(&spec, Some(&fp), &text, "draft").unwrap();
        assert!(m.geo.tri_count() > 50);
    }

    #[test]
    fn parts_replace_their_outline() {
        let fp = Footprint::parse(
            r#"{"anchor":[0,0],"outlines":[{"id":"way/1","tags":{"height":"34"},"outer":[[0,0],[20,0],[20,10],[0,10]]}],
            "parts":[{"id":"way/2","tags":{"building:part":"yes","height":"34"},"outer":[[0,0],[10,0],[10,10],[0,10]]},
                     {"id":"way/3","tags":{"building:part":"yes","building:levels":"2"},"outer":[[10,0],[20,0],[20,10],[10,10]]}],
            "context":[{"floors_above":4,"outer":[[0,10.5],[20,10.5],[20,20],[0,20]]}]}"#,
            "t",
        )
        .unwrap();
        let text = draft("x", Some(&fp), None);
        assert!(text.contains("enabled = false"), "{text}");
        // Edge 0 (z = 0, facing north) is the street; the south side backs onto a neighbour.
        assert!(text.contains("main_facade = 0"), "{text}");
        let spec = crate::landmark::parse::parse_spec(&text, "draft").unwrap();
        let m = crate::landmark::build::build(&spec, Some(&fp), &text, "draft").unwrap();
        let v = crate::landmark::metrics::compute(&m, Some(&fp), "x", 0.0);
        assert!(v["warnings"].as_array().unwrap().iter().all(|w| !w.as_str().unwrap().contains("too high")), "{v}");
    }
}
