//! Draft `landmark.toml` from the real data: one mass per OSM outline and
//! tagged part (heights from tags or Catastro floors), a roof from
//! `roof:shape`, and a `[[view]]` per photo with a known camera. A
//! starting point for modelling, never the final model.

use std::fmt::Write;

use super::footprint::{Footprint, FpPoly, Sources};
use super::poly;

fn esc(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

fn roof_shape(tag: Option<&str>) -> Option<&'static str> {
    Some(match tag? {
        "gabled" => "gable",
        "hipped" | "half-hipped" => "hip",
        "pyramidal" => "pyramid",
        "dome" | "onion" => "dome",
        "skillion" => "shed",
        "round" => "barrel",
        "cone" | "conical" => "cone",
        "mansard" => "mansard",
        _ => return None,
    })
}

/// Height estimate of an outline: OSM tags, else the tallest Catastro
/// parcel overlapping it.
fn height_of(p: &FpPoly, fp: &Footprint) -> (f32, &'static str) {
    if let Some(h) = p.tag_height() {
        return (h, "OSM height/levels tag");
    }
    let c = poly::centroid(&p.shape.outer);
    let floors = fp.catastro.iter().filter(|q| q.shape.contains(c) || p.shape.contains(poly::centroid(&q.shape.outer))).filter_map(|q| q.floors_above).fold(0.0f32, f32::max);
    if floors > 0.0 {
        return (floors * 3.2 + 1.0, "Catastro floors x 3.2 m + 1 m");
    }
    (12.0, "placeholder: no height data")
}

/// Draft spec text.
pub fn draft(slug: &str, fp: Option<&Footprint>, sources: Option<&Sources>) -> String {
    let mut s = String::new();
    let name = fp.and_then(|f| f.outlines.iter().find_map(|o| o.tag("name").map(|n| n.to_string()))).unwrap_or_else(|| slug.to_string());
    let _ = writeln!(s, "# Draft generated by `landmark init` from footprint.json: massing only.");
    let _ = writeln!(s, "# Refine following data/landmarks/README.md (roofs, towers, openings, details).\n");
    let _ = writeln!(s, "[landmark]\nname = \"{}\"\nslug = \"{}\"\nmain_facade = \"longest\"\n", esc(&name), esc(slug));
    let _ = writeln!(s, "[defaults]\nmaterial = \"stone\"\n");
    let _ = writeln!(s, "[material.stone]\nkind = \"ashlar\"\ntint = \"#e3d8c2\"\nweathering = 0.3\n");
    let _ = writeln!(s, "[material.roof]\nkind = \"roof_tiles\"\n");
    if let Some(fp) = fp {
        for (i, o) in fp.outlines.iter().enumerate() {
            let (h, why) = height_of(o, fp);
            let _ = writeln!(s, "[[element]]\ntype = \"mass\"\nname = \"outline{i}\"\npolygon = \"outline:{i}\"   # {} ({:.0} m2)\nheight = {:.1}   # {why}\ncornice = \"cornice\"", esc(&o.id), o.shape.area(), h);
            match roof_shape(o.tag("roof:shape")) {
                Some(r) => {
                    let _ = writeln!(s, "roof = {{ shape = \"{r}\", pitch = 30 }}\n");
                }
                None => {
                    let _ = writeln!(s);
                }
            }
        }
        for (i, p) in fp.parts.iter().enumerate() {
            let Some(h) = p.tag_height() else { continue };
            let y0 = p.tag_min_height().unwrap_or(0.0).max(0.0);
            if h <= y0 + 0.5 {
                continue;
            }
            let _ = writeln!(s, "[[element]]\ntype = \"mass\"\nname = \"part{i}\"\npolygon = \"part:{i}\"   # {} {}\ny0 = {:.1}\ny1 = {:.1}", esc(&p.id), esc(p.tag("building:part").unwrap_or("")), y0, h);
            if let Some(r) = roof_shape(p.tag("roof:shape")) {
                let _ = writeln!(s, "roof = {{ shape = \"{r}\" }}");
            }
            let _ = writeln!(s);
        }
        if fp.outlines.is_empty() {
            let _ = writeln!(s, "# footprint.json has no outlines: add masses with literal polygons.\n");
        }
    } else {
        let _ = writeln!(s, "# No footprint.json yet: add masses with literal polygons [[x, z], ...].\n");
    }
    if let Some(src) = sources {
        for p in &src.photos {
            match p.camera {
                Some(c) => {
                    let _ = writeln!(s, "[[view]]\nphoto = \"{}\"\neye = [{:.1}, 1.6, {:.1}]\ntarget = [0.0, 10.0, 0.0]   # aim at the main feature\nfocal_35mm = 28\n", esc(&p.file), c.x, c.y);
                }
                None => {
                    let _ = writeln!(s, "# [[view]]\n# photo = \"{}\"   # estimate eye/target from the photo (README)\n", esc(&p.file));
                }
            }
        }
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn draft_parses() {
        let fp = Footprint::parse(
            r#"{"anchor":[0,0],"outlines":[{"id":"way/9","tags":{"name":"Torre","height":"20","roof:shape":"pyramidal"},"outer":[[0,0],[8,0],[8,8],[0,8]]}],
            "parts":[{"id":"way/10","tags":{"building:part":"yes","height":"30","min_height":"20"},"outer":[[2,2],[6,2],[6,6],[2,6]]}]}"#,
            "t",
        )
        .unwrap();
        let src = Sources::parse("[[photo]]\nfile = \"photos/a.jpg\"\ncamera = [5.0, 40.0]\n").unwrap();
        let text = draft("torre", Some(&fp), Some(&src));
        let spec = crate::landmark::parse::parse_spec(&text, "draft").unwrap_or_else(|e| panic!("{e}\n{text}"));
        assert_eq!(spec.element.len(), 2);
        assert_eq!(spec.view.len(), 1);
        let m = crate::landmark::build::build(&spec, Some(&fp), &text, "draft").unwrap();
        assert!(m.geo.tri_count() > 50);
    }
}
